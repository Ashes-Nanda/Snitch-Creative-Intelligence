// ── Creative asset ───────────────────────────────────────────────────────────

/** The creative's asset, with a stable multi-stage fallback when it can't be loaded. */
export function CreativeThumb({ creative, className }: { creative: Creative; className?: string }) {
  const [src, setSrc] = useState(creative.assetUrl)
  const [failed, setFailed] = useState(false)

  const handleError = () => {
    if (src !== `/creatives/${creative.creativeId}.svg`) {
      setSrc(`/creatives/${creative.creativeId}.svg`)
    } else {
      setFailed(true)
    }
  }

  return (
    <span className={cn('relative block aspect-[4/5] shrink-0 overflow-hidden rounded-md border bg-muted', className)}>
      {failed ? (
        <span className="flex h-full w-full flex-col items-center justify-center gap-1 p-1 text-center text-[10px] text-muted-foreground">
          <ImageOff className="size-4" aria-hidden />
          Asset unavailable
        </span>
      ) : (
        <img src={src} alt={`Preview of ${creative.name}`} loading="lazy" onError={handleError} className="h-full w-full object-cover" />
      )}
    </span>
  )
}

// ── Confirm dialog ───────────────────────────────────────────────────────────

/**
 * Confirms a consequential decision. When `reason` is set, a reason field is shown (required or optional).
 * The dialog stays open and shows the error if the decision is refused.
 */
export function ConfirmDialog({
  open,
  onOpenChange,
  title,
  description,
  confirmLabel,
  destructive,
  reason,
  onConfirm,
}: {
  open: boolean
  onOpenChange: (open: boolean) => void
  title: string
  description: ReactNode
  confirmLabel: string
  destructive?: boolean
  reason?: { label: string; required: boolean; placeholder?: string }
  onConfirm: (reason: string) => { ok: true } | { ok: false; error: string }
}) {
  const [text, setText] = useState('')
  const [error, setError] = useState<string | null>(null)
  const close = (o: boolean) => {
    if (!o) {
      setText('')
      setError(null)
    }
    onOpenChange(o)
  }
  return (
    <Dialog open={open} onOpenChange={close}>
      <DialogContent>
        <form
          onSubmit={(e) => {
            e.preventDefault()
            if (reason?.required && !text.trim()) return setError(`${reason.label} is required.`)
            const outcome = onConfirm(text)
            if (outcome.ok) close(false)
            else setError(outcome.error)
          }}
          className="flex flex-col gap-4"
        >
          <DialogHeader>
            <DialogTitle>{title}</DialogTitle>
            <DialogDescription>{description}</DialogDescription>
          </DialogHeader>
          {reason && (
            <div className="flex flex-col gap-1.5">
              <Label htmlFor="confirm-reason">
                {reason.label}
                {!reason.required && <span className="font-normal text-muted-foreground"> (optional)</span>}
              </Label>
              <Textarea id="confirm-reason" value={text} onChange={(e) => setText(e.target.value)} placeholder={reason.placeholder} rows={3} aria-invalid={!!error} />
            </div>
          )}
          {error && (
            <p role="alert" className="text-sm text-destructive">
              {error}
            </p>
          )}
          <DialogFooter>
            <Button type="button" variant="outline" onClick={() => close(false)}>
              Cancel
            </Button>
            <Button type="submit" variant={destructive ? 'destructive' : 'default'}>
              {confirmLabel}
            </Button>
          </DialogFooter>
        </form>
      </DialogContent>
    </Dialog>
  )
}
