/** A metric value. An unavailable value shows a dash with the reason on hover, never zero. */
export function MetricValue({ value, format, unavailableReason, className }: { value: number | null; format: (v: number) => string; unavailableReason: string; className?: string }) {
  if (value !== null) return <span className={cn('tabular', className)}>{format(value)}</span>
  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <span tabIndex={0} aria-label={`Unavailable: ${unavailableReason}`} className={cn('cursor-help text-muted-foreground', className)}>
          {NA}
        </span>
      </TooltipTrigger>
      <TooltipContent className="max-w-64">{unavailableReason}</TooltipContent>
    </Tooltip>
  )
}

