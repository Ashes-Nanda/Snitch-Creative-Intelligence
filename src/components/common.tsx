// ── Status ───────────────────────────────────────────────────────────────────

type Tone = 'neutral' | 'info' | 'good' | 'warn' | 'bad'

const toneClass: Record<Tone, string> = {
  neutral: 'border-border bg-muted text-muted-foreground',
  info: 'border-blue-200 bg-blue-50 text-blue-800',
  good: 'border-green-200 bg-green-50 text-green-800',
  warn: 'border-amber-300 bg-amber-50 text-amber-900',
  bad: 'border-red-200 bg-red-50 text-red-800',
}

/** A status label: always text plus an icon, never colour alone. */
export function StatusBadge({ tone, icon: Icon, children, title }: { tone: Tone; icon?: typeof Info; children: ReactNode; title?: string }) {
  return (
    <Badge variant="outline" title={title} className={cn('gap-1 font-medium', toneClass[tone])}>
      {Icon && <Icon aria-hidden />}
      {children}
    </Badge>
  )
}

export const proposalStatusMeta: Record<ProposalStatus, { label: string; tone: Tone; icon: typeof Info }> = {
  draft: { label: 'Draft', tone: 'neutral', icon: CircleDashed },
  needs_review: { label: 'Needs review', tone: 'info', icon: Clock },
  approved: { label: 'Approved', tone: 'good', icon: CheckCircle2 },
  rejected: { label: 'Rejected', tone: 'bad', icon: XCircle },
  completed: { label: 'Completed', tone: 'good', icon: FlaskConical },
  not_run: { label: 'Not run', tone: 'neutral', icon: CircleSlash },
}

export function ProposalStatusBadge({ status }: { status: ProposalStatus }) {
  const m = proposalStatusMeta[status]
  return (
    <StatusBadge tone={m.tone} icon={m.icon}>
      {m.label}
    </StatusBadge>
  )
}

export function EvidenceBadge({ level }: { level: EvidenceLevel | 'insufficient' }) {
  if (level === 'supported')
    return (
      <StatusBadge tone="good" icon={CheckCircle2} title="Clears the evidence bar and is not confounded with another pattern.">
        Supported
      </StatusBadge>
    )
  if (level === 'hypothesis')
    return (
      <StatusBadge tone="warn" icon={Sparkles} title="Clears the evidence bar, but overlaps another pattern, so the data can’t single it out.">
        Hypothesis
      </StatusBadge>
    )
  return (
    <StatusBadge tone="neutral" icon={CircleSlash}>
      Insufficient evidence
    </StatusBadge>
  )
}

export function StaleBadge({ reason }: { reason: string }) {
  return (
    <StatusBadge tone="warn" icon={AlertTriangle} title={reason}>
      Stale
    </StatusBadge>
  )
}

export function AnalysisBadge({ status }: { status: AnalysisStatus | undefined }) {
  if (status === 'complete') return <StatusBadge tone="neutral" icon={Bot}>Analysed</StatusBadge>
  if (status === 'failed') return <StatusBadge tone="bad" icon={XCircle}>Analysis failed</StatusBadge>
  return <StatusBadge tone="neutral" icon={CircleDashed}>Not analysed</StatusBadge>
}

